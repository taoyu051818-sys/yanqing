/** 已消课明细：合计确认收入需与 enrollments.confirmedRevenue 对齐 */
export const seedSessionLogs = (): TrainingSessionLog[] => {
  const logs: TrainingSessionLog[] = []
  const plan: { en: TrainingEnrollment; courseId: string; count: number; startDay: number }[] = []
  const enrollments = seedEnrollments()
  const courses = seedCourses()
  enrollments.forEach((en) => {
    plan.push({ en, courseId: en.courseId, count: en.usedSessions, startDay: 1 })
  })
  let seq = 1
  plan.forEach(({ en, count }) => {
    const course = courses.find((c) => c.id === en.courseId)!
    for (let i = 0; i < count; i++) {
      const day = 2 + i * 3
      const date = `2026-0${day > 30 ? 7 : 8}-${String(((day - 1) % 28) + 1).padStart(2, '0')}`
      logs.push({
        id: `SL${String(seq++).padStart(4, '0')}`,
        enrollmentId: en.id,
        courseId: en.courseId,
        studentName: en.studentName,
        date,
        courtCount: course.courtCountPerSession,
        hours: course.hoursPerSession,
        confirmedAmount: en.unitPrice,
        coachCost: course.coachCostPerSession,
        materialCost: course.materialCostPerSession,
        operator: course.coach,
        at: `${date} 19:40`,
      })
    }
  })
  return logs
}

