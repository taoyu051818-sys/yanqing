// Local mock-only UI regression. Never connects to the production API.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.CLOSEOUT_BASE || 'http://127.0.0.1:5193'
const output = path.resolve(process.env.CLOSEOUT_OUTPUT || 'artifacts/journey-closeout')
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-gpu'] })
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  await context.addInitScript(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async payload => { window.__sharePayload = payload } }))
  const errors = [], checks = [], screenshots = []
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort())
  const p = await context.newPage()
  p.setDefaultTimeout(12000)
  p.on('pageerror', error => errors.push(error.message))
  const body = () => p.locator('body').innerText()
  const click = value => p.getByText(value, { exact: true }).last().click()
  const first = value => p.getByText(value, { exact: true }).first().click()
  const put = (key, data) => p.evaluate(({ key, data }) => localStorage.setItem(key, JSON.stringify({ type: 'object', data })), { key, data })
  const read = key => p.evaluate(key => { const raw = localStorage.getItem(key); try { return JSON.parse(raw)?.data } catch { return raw } }, key)
  const go = async route => { await p.goto(base + '/#' + route); await p.reload(); await p.waitForTimeout(850) }
  const role = async name => p.evaluate(name => {
    localStorage.setItem('yanqing_mock_role', name)
    localStorage.setItem('yanqing_access_token', 'mock-token-' + name.toLowerCase())
    localStorage.removeItem('yanqing_actor_id')
  }, name)
  const task = () => p.locator('#operation-task')
  const input = key => p.locator('#task-field-' + key + ' input, #task-field-' + key + ' textarea')
  const finish = async () => {
    await task().locator('.task-actions .primary').click()
    await task().locator('.task-result').waitFor()
    assert.equal(await p.locator('uni-modal:visible').count(), 0)
  }
  const dismiss = () => click('知道了，继续处理')
  const snap = async (name, form = true) => {
    await p.waitForTimeout(400)
    if (form) await task().scrollIntoViewIfNeeded()
    const overflow = await p.evaluate(() => {
      const root = document.querySelector('.ops-page') || document.querySelector('.page')
      if (!root) return ['missing page']
      const bounds = root.getBoundingClientRect()
      return [...root.querySelectorAll('uni-button, #operation-task, #operation-task uni-input, #operation-task uni-textarea')]
        .filter(el => { if (el.closest('.product-scroll')) return false; const r = el.getBoundingClientRect(); return r.width && r.height && (r.left < bounds.left - 3 || r.right > bounds.right + 3 || el.scrollWidth > el.clientWidth + 5) })
        .map(el => el.className)
    })
    assert.deepEqual(overflow, [], name + ' overflow')
    if (form) {
      const targets = await task().locator('uni-button').evaluateAll(els => els.filter(el => el.getBoundingClientRect().height < 43).map(el => el.textContent))
      assert.deepEqual(targets, [], name + ' touch targets')
      await task().screenshot({ path: path.join(output, name + '.png') })
    } else await p.screenshot({ path: path.join(output, name + '.png'), fullPage: false })
    screenshots.push(name)
  }
  try {
    await go('/pages/home/index'); await role('SUPER_ADMIN')
    await go('/packages/ops/pages/members/index'); await click('客户线索'); await first('分配')
    await task().locator('.task-options uni-button').first().waitFor()
    assert(!(await task().innerText()).includes('user-'))
    await snap('01-staff-directory-by-name')
    await task().locator('.task-options uni-button').first().click(); await finish(); await dismiss()
    assert((await read('yanqing_mock_customer_leads'))[0].ownerId)
    checks.push('lead-owner-selection-persists-without-pasting-id')
    await first('跟进推进'); await input('content').fill('电话核对可到店体验')
    await task().getByText('已约体验', { exact: true }).click(); await finish()
    assert.equal((await read('yanqing_mock_customer_leads'))[0].status, 'TRIAL_RESERVED')
    checks.push('followup-explicit-stage-and-communication-record')

    await go('/packages/ops/pages/merchant/index')
    await first('设置适用范围'); await input('reason').fill('本轮验收：商户券仅限本店消费')
    await snap('02-coupon-scope-explicit-policy'); await finish(); await dismiss()
    assert.equal((await read('yanqing_mock_coupon_templates'))[0].allowVenueBooking, false)
    await first('批量发行唯一券'); await input('count').fill('0')
    await task().locator('.task-actions .primary').click()
    assert((await task().innerText()).includes('超出允许范围'))
    await snap('03-batch-quantity-inline-validation')
    await input('count').fill('3'); await finish(); await dismiss()
    assert.equal(await p.getByText('分享领取链接', { exact: true }).count(), 3)
    await first('分享领取链接')
    const share = await p.evaluate(() => window.__sharePayload)
    assert(share.url.includes('/#/pages/coupon/index?claim='))
    checks.push('batch-issue-three-unique-cards-and-native-share-payload')
    await role('MEMBER'); await go(share.url.split('/#')[1])
    assert.equal(await p.locator('.claim input').count(), 1)
    await click('确认领取'); await p.waitForTimeout(550)
    assert((await body()).includes('不可抵扣订场'))
    await snap('04-recipient-opens-card-and-claims', false)
    checks.push('coupon-card-direct-claim-merchant-only')

    await role('COACH'); await go('/packages/ops/pages/coach/index')
    await click('到场'); await click('已核对本人到场'); await finish(); await dismiss()
    await click('提交消课建议'); await input('feedback').fill('已完成步法与双打轮转训练')
    await snap('05-coach-consumption-proposal'); await finish(); await dismiss()
    let enrollment = (await read('yanqing_mock_enrollments'))[0]
    assert.equal(enrollment.usedSessions, 3)
    checks.push('coach-proposal-does-not-debit-before-independent-review')
    await role('SUPER_ADMIN'); await go('/packages/ops/pages/coach/index')
    await click('确认入账'); await click('已核对点名与教练反馈')
    await snap('06-independent-consumption-confirmation'); await finish(); await dismiss()
    enrollment = (await read('yanqing_mock_enrollments'))[0]
    assert.equal(enrollment.usedSessions, 4)
    checks.push('independent-review-debits-one-lesson-and-recognition')
    await click('申请冲正'); await input('reason').fill('核对出勤发现课次选择错误，请冲正原记录'); await snap('07-correction-reason-and-proof')
    await finish(); await dismiss()
    assert.equal(await p.getByText('批准冲正', { exact: true }).getAttribute('disabled'), 'true')
    await role('ADMIN'); await go('/packages/ops/pages/coach/index')
    await click('批准冲正'); await input('reason').fill('已核对原点名表与课程记录，批准冲正')
    await finish()
    assert.equal((await read('yanqing_mock_enrollments'))[0].usedSessions, 3)
    checks.push('correction-independent-approval-restores-lesson-and-keeps-ledger')
    await snap('08-coach-after-correction', false)

    await role('SUPER_ADMIN'); await go('/packages/ops/pages/event/index')
    await click('录入比分'); await input('scoreA').fill('21'); await input('scoreB').fill('21')
    await task().locator('.task-actions .primary').click()
    await p.waitForTimeout(200)
    assert((await task().innerText()).includes('不得并列'))
    assert.equal(await input('scoreA').inputValue(), '21')
    await snap('09-score-error-retains-both-fields')
    await input('scoreB').fill('18'); await finish(); await dismiss()
    assert.equal(await p.getByText('录入比分', { exact: true }).count(), 0)
    checks.push('score-entry-validates-and-unlocks-next-round')
    await first('纠错'); await input('reason').fill('现场复核纸质记分表')
    await input('scoreB').fill('15'); await finish()
    checks.push('score-correction-recalculates-with-reason')

    await go('/packages/ops/pages/finance/index'); await click('生成账期草稿')
    await input('marketing').fill('1.234'); await task().locator('.task-actions .primary').click()
    assert((await task().innerText()).includes('最多两位小数'))
    await input('marketing').fill('12.50')
    await p.waitForTimeout(50)
    assert(!(await task().innerText()).includes('最多两位小数'))
    await snap('10-finance-costs-one-form')
    await p.setViewportSize({ width: 320, height: 720 }); await snap('11-finance-form-320')
    await p.setViewportSize({ width: 812, height: 375 }); await snap('12-finance-form-landscape')
    await p.setViewportSize({ width: 375, height: 812 }); await click('暂不处理')
    checks.push('finance-money-validation-and-mobile-form-layout')

    await put('yanqing_mock_stocktakes', [{ id: 'stocktake-closeout', stocktakeNo: 'ST-CLOSEOUT', status: 'COUNTING', locationId: 'location-main', createdById: 'user-admin', createdAt: new Date().toISOString(), lines: [{ id: 'count-closeout', itemId: 'goods-ball', item: { name: '金羽训练羽毛球' }, bookQuantity: 36, countedQuantity: null }] }])
    await go('/packages/ops/pages/inventory/index'); await click('盘点'); await click('录入下一项')
    await input('counted').fill('0'); await snap('13-stocktake-zero-quantity'); await finish()
    assert.equal((await read('yanqing_mock_stocktakes'))[0].lines[0].countedQuantity, 0)
    checks.push('inventory-zero-count-saves-without-posting-difference')

    await go('/packages/ops/pages/frontdesk/index'); await click('开班')
    await snap('14-frontdesk-opening-float')
    await input('amount').fill('0'); await finish(); await dismiss()
    assert.equal((await read('yanqing_mock_front_desk_shifts'))[0].status, 'OPEN')
    checks.push('frontdesk-opening-cash-recorded')
    await go('/packages/ops/pages/venue/index'); await first('停用规则'); await snap('15-venue-rule-reason'); await click('暂不处理')
    await go('/packages/ops/pages/host/index'); await click('取消球局并发起退款'); await snap('16-host-cancel-impact-review'); await click('暂不处理')
    await go('/packages/ops/pages/governance/index'); await snap('17-governance-role-management', false)
    checks.push('remaining-venue-host-governance-surfaces-no-blank-or-overflow')
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ status: 'PASS', checks, screenshots, errors }, null, 2))
    console.log(JSON.stringify({ status: 'PASS', checks: checks.length, screenshots: screenshots.length, output }))
  } catch (error) {
    console.error(await body())
    await p.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
