// Isolated browser/mock regression: never connects to or writes the live API.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.FRICTION_BASE || 'http://127.0.0.1:5193'
const output = path.resolve(process.env.FRICTION_OUTPUT || 'artifacts/low-friction')
;(async () => {
  await fs.mkdir(output, { recursive: true })
  // Software rendering avoids dropped glyphs in full-page headless captures
  // after editing inputs and changing viewport size.
  const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--disable-gpu'] })
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] })
  // Exercise the clipboard fallback deterministically. OS share sheets cannot
  // be accepted from a headless browser; the share payload branch is checked below.
  await context.addInitScript(() => Object.defineProperty(navigator, 'share', { configurable: true, value: undefined }))
  const errors = [], checks = []
  await context.route('**/*', route => {
    const origin = new URL(route.request().url()).origin
    if (origin === base || origin === 'null') return route.continue()
    errors.push('Unexpected external request: ' + origin)
    return route.abort()
  })
  const page = await context.newPage()
  page.setDefaultTimeout(12000)
  page.on('pageerror', error => errors.push(error.message))
  const text = () => page.locator('body').innerText()
  const click = value => page.getByText(value, { exact: true }).last().click()
  const go = async route => { await page.goto(base + '/#' + route); await page.reload(); await page.waitForTimeout(700) }
  const read = key => page.evaluate(key => { const v = localStorage.getItem(key); if (!v) return null; try { return JSON.parse(v).data } catch { return v } }, key)
  const put = (key, value) => page.evaluate(({ key, value }) => localStorage.setItem(key, JSON.stringify({ type: 'object', data: value })), { key, value })
  const snap = async name => {
    await page.waitForTimeout(1600)
    const font = await page.evaluate(() => ({
      root: getComputedStyle(document.documentElement).fontSize,
      heading: document.querySelector('.banner-title') && getComputedStyle(document.querySelector('.banner-title')).fontSize,
      inline: document.documentElement.style.fontSize,
    }))
    assert(parseFloat(font.root) >= 10, 'Root font must not collapse')
    if (font.heading) assert(parseFloat(font.heading) >= 12, 'Course heading must remain readable')
    const overflow = await page.evaluate(() => {
      const root = [...document.querySelectorAll('.page, .ops-page')].find(el => el.getBoundingClientRect().width)
      if (!root) return ['missing page']
      const bounds = root.getBoundingClientRect()
      return [...root.querySelectorAll('uni-button, uni-input, .reason-form, .payment-selection, .enroll-form, .product, .card')]
        .filter(el => {
          if (el.closest('.matrix-wrap')) return false
          const r = el.getBoundingClientRect()
          // Coupon edge cutouts deliberately extend into the clipped card edge;
          // check its bounds and every interactive child, not that decoration.
          return r.width && r.height && (r.left < bounds.left - 3 || r.right > bounds.right + 3 || (!el.matches('.coupon.card') && el.scrollWidth > el.clientWidth + 4))
        }).map(el => el.className)
    })
    assert.deepEqual(overflow, [], name)
    await page.screenshot({ path: path.join(output, name + '.png'), fullPage: true })
    checks.push(name)
  }
  async function pay(channel = 'WECHAT') {
    await click('立即支付')
    await page.waitForTimeout(450)
    if (channel !== 'WECHAT') await page.locator('.payment-choice').filter({ hasText: '充值余额' }).click()
    await page.locator('.payment-selection .primary').click()
    await page.waitForTimeout(800)
    assert(/已支付|已完成/.test(await text()))
  }
  try {
    await go('/pages/home/index')
    await page.evaluate(() => { localStorage.setItem('yanqing_mock_role', 'MEMBER'); localStorage.setItem('yanqing_access_token', 'mock-token-member') })
    await go('/pages/membership/index')
    await snap('01-recharge-separated-assets')
    await click('¥100.00 · 下一步付款')
    await page.waitForURL('**/pages/order/index?id=**')
    await click('立即支付'); await page.waitForTimeout(450)
    assert.equal(await page.locator('.payment-choice').count(), 4)
    assert.equal(await page.locator('.payment-choice:not([disabled])').count(), 1)
    await snap('02-recharge-wechat-only')
    await page.locator('.payment-selection .primary').click(); await page.waitForTimeout(750)
    assert((await text()).includes('已完成'))
    assert.equal((await read('yanqing_mock_member_accounts'))['user-member'].find(item => item.type === 'CASH_PRINCIPAL').balance, 138000)
    checks.push('recharge-to-exact-order-and-paid-state')
    await go('/pages/shop/index')
    const product = page.locator('.product').first()
    await product.locator('[aria-label="增加金羽训练羽毛球数量"]').click()
    assert((await product.innerText()).includes('合计 ¥176.00'))
    await snap('03-shop-quantity-subtotal-375')
    await page.setViewportSize({ width: 320, height: 720 }); await snap('04-shop-320')
    await page.setViewportSize({ width: 1280, height: 800 }); await snap('05-shop-desktop-phone-layout')
    await page.setViewportSize({ width: 375, height: 812 })
    await product.getByText('下单，下一步付款', { exact: true }).click()
    await page.waitForURL('**/pages/order/index?id=**')
    await pay('CASH_PRINCIPAL')
    await click('申请退款'); await click('行程有变')
    await snap('06-order-refund-one-form')
    await click('确认申请退款'); await page.waitForTimeout(700)
    assert((await text()).includes('退款申请处理中'))
    checks.push('goods-purchase-payment-refund-state')
    await go('/pages/training/index')
    await page.getByText('选择报名', { exact: true }).first().click()
    assert((await text()).includes('周三晚进阶班 · 点击选择'))
    await snap('07-training-class-and-student-selection')
    await click('确认报名，下一步付款')
    await page.getByText('该学员已报名本班或仍在名额保留期内', { exact: true }).waitFor()
    assert((await text()).includes('周三晚进阶班 · 点击选择'))
    checks.push('duplicate-enrollment-blocked-and-selection-retained')
    // Remove only this isolated context's seeded enrollment to test a new purchase.
    await put('yanqing_mock_enrollments', [])
    await click('确认报名，下一步付款')
    await page.waitForURL('**/pages/order/index?id=**')
    await pay()
    await click('查看课程与退费'); await page.waitForTimeout(650)
    await page.getByText('申请退费', { exact: true }).last().click()
    await page.locator('.reason-form').waitFor()
    await click('时间不合适'); await click('指定退费金额')
    await page.locator('.refund-amount input').fill('999999')
    await click('确认申请退费')
    assert((await text()).includes('请输入 0.01 至'))
    assert.equal(await page.locator('.reason-options .selected').innerText(), '时间不合适')
    await click('全部可退余额 ¥1280.00')
    await snap('08-training-refund-amount-and-reason')
    await click('确认申请退费')
    await page.waitForURL('**/pages/order/index?id=**')
    await page.waitForTimeout(550)
    assert((await text()).includes('退款申请处理中'))
    checks.push('training-purchase-pay-refund-and-retained-validation')
    await go('/pages/coupon/index')
    await click('其他领券方式：输入券码')
    await page.locator('.claim input').fill('YQ-COFFEE-2026')
    await click('确认领取'); await page.waitForTimeout(700)
    assert((await text()).includes('不可抵扣订场'))
    assert.equal(await page.getByText('选择场地，使用此券', { exact: true }).count(), 0)
    checks.push('existing-merchant-coupon-no-longer-discounts-booking')
    // Explicitly enabled venue coupon; this is not grandfathering a merchant coupon.
    const coupons = await read('yanqing_mock_coupons')
    coupons[0].template.allowVenueBooking = true
    if (coupons[0].templateId) {
      const templates = await read('yanqing_mock_coupon_templates')
      templates.find(item => item.id === coupons[0].templateId).allowVenueBooking = true
      await put('yanqing_mock_coupon_templates', templates)
    }
    await put('yanqing_mock_coupons', coupons)
    await go('/pages/coupon/index')
    await page.getByText('选择场地，使用此券', { exact: true }).waitFor()
    await snap('09-wallet-use-coupon-directly')
    await click('选择场地，使用此券')
    await page.waitForURL('**/pages/booking/index')
    await page.waitForTimeout(700)
    await page.locator('.court:not(.disabled)').first().click()
    await page.locator('.confirm').scrollIntoViewIfNeeded()
    assert((await text()).includes('已选：'))
    assert.equal(await page.locator('.confirm input').count(), 0)
    await snap('10-booking-coupon-selected-without-code')
    await click('确认预约，下一步付款')
    await page.waitForURL('**/pages/order/index?id=**')
    const booking = (await read('yanqing_mock_orders')).find(item => item.id === new URL(page.url().replace('#', '')).searchParams.get('id'))
    assert(booking && booking.discountCents === 2000)
    checks.push('coupon-to-booking-to-discounted-order')
    await go('/pages/invite/index')
    await snap('11-referral-share-link-not-opaque-code')
    assert(!(await text()).includes('复制邀请码'))
    await click('分享邀请链接'); await page.waitForTimeout(350)
    const invitation = await page.evaluate(() => navigator.clipboard.readText())
    assert(invitation.startsWith(base + '/#/pages/home/index?invite='))
    assert(!invitation.includes('user-member'))
    checks.push('referral-uses-openable-invitation-link')
    await page.evaluate(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async payload => { window.__sharePayload = payload } }))
    await click('分享邀请链接'); await page.waitForTimeout(250)
    assert.equal((await page.evaluate(() => window.__sharePayload)).url, invitation)
    checks.push('browser-native-share-receives-the-same-safe-link')
    // Test youth enrollment resume without requiring a second selection.
    await put('yanqing_mock_students', [])
    await go('/pages/training/index')
    await page.getByText('选择报名', { exact: true }).last().click()
    await page.locator('.student-form input').first().fill('验收小学员')
    await page.locator('.consent-row uni-switch').click()
    await click('保存并完成授权'); await page.waitForTimeout(700)
    assert((await text()).includes('验收小学员 · 点击选择'))
    await snap('12-new-student-resumes-selected-course')
    await page.setViewportSize({ width: 320, height: 720 }); await snap('13-training-form-320')
    await page.setViewportSize({ width: 812, height: 375 }); await snap('14-training-form-landscape')
    await page.setViewportSize({ width: 375, height: 812 })
    const event = { id: 'event-friction', name: '流程验收候补赛', status: 'OPEN', capacityPeople: 24, minimumPeople: 24, totalRounds: 5, currentRound: 0, feeCents: 9900, startsAt: new Date(Date.now() + 7 * 86400000).toISOString(), registrationEndsAt: new Date(Date.now() + 6 * 86400000).toISOString(), rounds: [], teams: [{ id: 'team-friction', name: '验收搭档', captainId: 'user-member', playerAUserId: 'user-member', playerAName: '测试甲', playerBName: '测试乙', category: 'MIXED_DOUBLES', status: 'WAITLISTED', createdAt: new Date().toISOString() }] }
    await put('yanqing_mock_events', [event])
    await put('yanqing_mock_event_details', { [event.id]: event })
    await go('/pages/community/index?tab=events&view=mine')
    await click('查看我的报名')
    await click('退出报名'); await click('行程有变')
    await snap('15-event-withdrawal-inline-confirmation')
    await click('确认退出报名'); await page.waitForTimeout(800)
    assert.equal((await read('yanqing_mock_event_details'))[event.id].teams[0].status, 'CANCELLED')
    checks.push('event-withdrawal-releases-waitlist-without-dialog-chain')
    await page.evaluate(() => { localStorage.setItem('yanqing_mock_role', 'FRONT_DESK'); localStorage.setItem('yanqing_access_token', 'mock-token-front_desk') })
    const now = Date.now()
    const bookingRecord = { id: 'booking-friction', orderId: 'fulfill-friction', courtId: 'court-1', status: 'CHECKED_IN', startsAt: new Date(now - 70 * 60000).toISOString(), endsAt: new Date(now - 10 * 60000).toISOString(), checkedInAt: new Date(now - 65 * 60000).toISOString() }
    await put('yanqing_mock_orders', [{ id: 'fulfill-friction', orderNo: 'LOCAL-FULFILL', title: '验收场地履约', businessType: 'VENUE', status: 'CHECKED_IN', memberId: 'user-member', member: { displayName: '测试会员' }, payableCents: 8800, paidCents: 8800, refundedCents: 0, createdAt: new Date(now - 90 * 60000).toISOString(), bookings: [bookingRecord] }])
    await put('yanqing_mock_venue_bookings', [bookingRecord])
    await put('yanqing_mock_front_desk_shifts', [{ id: 'shift-friction', status: 'OPEN', venueCode: 'MAIN', operatorId: 'user-frontdesk', businessDateLabel: new Date(now + 8 * 3600000).toISOString().slice(0, 10), openingCashCents: 0, openedAt: new Date(now - 3600000).toISOString(), auditTrail: [] }])
    await go('/packages/ops/pages/frontdesk/index')
    await click('确认完成'); await click('巡场确认使用已结束')
    await page.locator('.reason-form').scrollIntoViewIfNeeded()
    await snap('16-frontdesk-fulfillment-reason-selection')
    await click('确认并记录'); await page.waitForTimeout(750)
    assert.equal((await read('yanqing_mock_orders'))[0].status, 'COMPLETED')
    assert((await read('yanqing_mock_audit_logs')).some(item => item.objectId === 'fulfill-friction'))
    checks.push('frontdesk-fulfillment-updates-order-and-audit')
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ status: 'PASS', checks }, null, 2))
    console.log(JSON.stringify({ status: 'PASS', count: checks.length, output }))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true })
    console.error(await text())
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
