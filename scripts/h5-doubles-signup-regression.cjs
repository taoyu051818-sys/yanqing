// Browser-only acceptance against an isolated local mock build.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = 'http://127.0.0.1:5192'
const output = path.resolve(process.env.DOUBLES_OUTPUT || 'artifacts/doubles-signup')
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
  const errors = [], checks = []
  await context.route('**/*', route => {
    const origin = new URL(route.request().url()).origin
    if (origin === base || origin === 'null') return route.continue()
    errors.push('Unexpected external request: ' + origin)
    return route.abort()
  })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  const go = async route => { await page.goto(base + '/#' + route); await page.reload(); await page.waitForTimeout(850) }
  const input = key => page.locator('#' + key + ' input')
  const click = text => page.getByText(text, { exact: true }).last().click()
  async function role(name) {
    await page.evaluate(role => {
      localStorage.setItem('yanqing_mock_role', role)
      localStorage.setItem('yanqing_access_token', 'mock-token-' + role.toLowerCase())
    }, name)
  }
  async function snapshot(name) {
    const problems = await page.evaluate(() => {
      const root = document.querySelector('.signup-page')
      if (!root) return []
      const bounds = root.getBoundingClientRect()
      return [...root.querySelectorAll('.panel, .identity-copy, uni-button, uni-input, .consent')].filter(node => {
        const box = node.getBoundingClientRect()
        return box.width && box.height && (box.left < bounds.left - 2 || box.right > bounds.right + 2 || node.scrollWidth > node.clientWidth + 3)
      }).map(node => node.className)
    })
    assert.deepEqual(problems, [])
    assert(!/CST|GMT|Invalid Date/.test(await page.locator('body').innerText()))
    await page.screenshot({ path: path.join(output, name + '.png') })
    checks.push(name)
  }
  try {
    await go('/pages/home/index')
    await role('MEMBER')
    await go('/pages/event-signup/index?id=event-open-partner')
    await input('team-name').waitFor()
    await snapshot('01-manual-signup-375')
    await page.setViewportSize({ width: 320, height: 720 }); await snapshot('02-manual-signup-320')
    await page.setViewportSize({ width: 812, height: 375 }); await snapshot('03-manual-signup-landscape')
    await page.setViewportSize({ width: 375, height: 812 })
    await input('team-name').fill('浏览器验收双打队')
    await input('playerAName').fill('张甲')
    await input('playerAPhone').fill('13810000001')
    await input('playerBName').fill('李乙')
    await input('playerBPhone').fill('13810000002')
    await page.getByText('我已征得两位选手同意，确认资料准确，并授权场馆用于本次报名。', { exact: true }).click()
    await snapshot('04-participant-contacts-and-consent')
    await click('核对并提交报名')
    await click('确认提交')
    await page.waitForURL('**/pages/order/index?id=**')
    await page.waitForTimeout(800)
    assert((await page.locator('body').innerText()).includes('待付款'))
    await snapshot('05-created-order-pending-payment')
    // Reset only this disposable browser context's mock fixtures, never the
    // user's existing browser profile or operating database.
    await page.evaluate(() => localStorage.clear())
    await role('MEMBER')
    await go('/pages/event-signup/index?id=event-open-partner')
    await click('微信邀请搭档')
    await input('team-name').fill('卡片邀请验收队')
    await input('playerAName').fill('张甲')
    await input('playerAPhone').fill('13810000001')
    await page.getByText('我确认本人参赛信息准确，并同意用于本次组队和赛事报名。', { exact: true }).click()
    await click('生成搭档邀请卡片')
    await page.waitForURL('**invite=**')
    await page.waitForTimeout(800)
    const inviteUrl = page.url()
    assert(!/138100|Phone|Name/.test(inviteUrl))
    assert((await page.locator('body').innerText()).includes('等待搭档确认'))
    await snapshot('06-captain-invite-pending')
    await page.evaluate(() => localStorage.removeItem('yanqing_access_token'))
    await page.reload(); await page.waitForTimeout(700)
    assert((await page.locator('body').innerText()).includes('登录并继续确认'))
    assert(!(await page.locator('body').innerText()).includes('138100'))
    await snapshot('07-public-invitation-preview')
    await click('登录并继续确认')
    await page.waitForURL('**/pages/login/index')
    const pending = await page.evaluate(() => localStorage.getItem('yanqing_member_login_return'))
    assert(pending.includes('invite='))
    checks.push('login-retains-invitation-deep-link')
    await role('HOST')
    await page.goto(inviteUrl); await page.reload(); await page.waitForTimeout(800)
    await input('partner-name').fill('李乙')
    await input('partner-phone').fill('13810000002')
    await page.getByText('我同意与该队长组队，并授权场馆使用以上资料联系和办理本次报名。', { exact: true }).click()
    await snapshot('08-partner-explicit-confirmation')
    await click('确认成为搭档')
    await page.getByText('组队已确认，请提醒队长提交报名并支付。', { exact: true }).waitFor()
    await snapshot('09-partner-confirmed-no-order-yet')
    await role('MEMBER')
    await page.reload(); await page.waitForTimeout(800)
    assert((await page.locator('body').innerText()).includes('选手二：李乙'))
    await snapshot('10-captain-ready-to-submit')
    await click('提交两人报名'); await click('确认提交')
    await page.waitForURL('**/pages/order/index?id=**'); await page.waitForTimeout(800)
    assert((await page.locator('body').innerText()).includes('待付款'))
    checks.push('invited-team-creates-single-pending-order')
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ status: 'PASS', checks }, null, 2))
    console.log(JSON.stringify({ status: 'PASS', count: checks.length, output }))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png') })
    console.error(await page.locator('body').innerText())
    throw error
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
