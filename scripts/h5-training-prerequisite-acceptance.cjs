const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.OPS_UI_BASE_URL || 'http://127.0.0.1:5208';
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Use a local mock build');
const dir = path.resolve(process.env.OPS_UI_OUTPUT_DIR || 'output/ui-acceptance', 'training');
fs.mkdirSync(dir, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ timezoneId: "Asia/Shanghai", viewport: { width: 375, height: 812 } });
  await page.clock.setFixedTime(new Date("2030-09-26T09:00:00+08:00"));
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort());
  const go = async route => { await page.goto(base + '/#' + route); await page.reload(); await page.waitForTimeout(1600); };
  const visible = () => page.locator('uni-page:visible');
  const button = text => visible().locator('uni-button').filter({ hasText: new RegExp('^\\s*' + text + '\\s*$') });
  const screenshot = async name => { await page.waitForTimeout(1700); return page.screenshot({ path: path.join(dir, name + '.png'), fullPage: true }); };
  try {
    await go('/packages/admin/pages/switch/index');
    assert(await page.evaluate(async () => (await import('/src/services/http.ts')).isMockMode));
    await page.getByText('超级管理端', { exact: true }).click();
    await page.waitForTimeout(800);
    await page.evaluate(async () => { const m = await import('/src/services/mock/state.ts'); m.saveTrainingSessions([]); });
    await go('/packages/ops/pages/coach/index?view=create-trial');
    await visible().locator('.member-option').first().click();
    await button('添加备注（选填）').click();
    await visible().locator('textarea').fill('新手，第一次到馆');
    const person = await visible().locator('.selected-person').innerText();
    assert((await visible().innerText()).includes('暂无可预约的上课时间'));
    await screenshot('01-trial-needs-session');
    await button('去排课').click();
    await page.waitForTimeout(1000);
    assert(page.url().includes('view=create-session'));
    assert(page.url().includes('classId='));
    await visible().locator('.court-choice:not(.blocked)').first().click();
    await screenshot('02-schedule-prefilled');
    await button('创建培训课次').click();
    await page.getByText('确认排课', { exact: true }).click();
    await page.waitForTimeout(1800);
    assert(page.url().includes('view=create-trial'));
    assert.equal(await visible().locator('.selected-person').innerText(), person);
    assert.equal(await visible().locator('textarea').inputValue(), '新手，第一次到馆');
    assert(!(await visible().innerText()).includes('请选择上课时间'));
    assert(!(await visible().innerText()).includes('暂无可预约的上课时间'));
    const session = await page.evaluate(async () => (await import('/src/services/mock/state.ts')).getTrainingSessions()[0]);
    assert(session.id);
    await screenshot('03-trial-returned-with-session');
    await button('预约试听').click();
    await page.waitForTimeout(1000);
    const trial = await page.evaluate(async () => (await import('/src/services/mock/state.ts')).getTrainingTrials().at(-1));
    assert.equal(trial.sessionId, session.id);
    assert.equal(trial.transitions[0].reason, '新手，第一次到馆');
    await go('/packages/ops/pages/coach/index?view=create-class');
    await page.evaluate(async () => { const m = await import('/src/services/mock/state.ts'); m.saveTrainingProducts([]); });
    await page.reload(); await page.waitForTimeout(1400);
    await visible().locator('#training-className input').fill('验收周末班');
    await button('去建课程').click();
    await page.waitForTimeout(1000);
    await visible().locator('#training-productName input').fill('验收成人基础课');
    await button('创建并上架').click();
    await page.waitForTimeout(1600);
    assert(page.url().includes('view=create-class'));
    assert.equal(await visible().locator('#training-className input').inputValue(), '验收周末班');
    assert((await visible().innerText()).includes('验收成人基础课'));
    await screenshot('04-class-returned-with-course');
    await page.setViewportSize({ width: 812, height: 375 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert((await visible().locator('.save-bar').boundingBox()).height < 150);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await screenshot('05-landscape-class');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(dir, 'result.json'), JSON.stringify({ passed: true, checks: ['试听补排课后按新课次 ID 返回', '学员与备注保留', '真实 mock 预约绑定新课次', '建课程返回班级表单并保留班级名', '375px 与横屏', '无浏览器运行异常'] }, null, 2));
    console.log('PASS training prerequisite return and draft preservation');
  } catch (error) { await screenshot('failure'); console.log((await page.locator('body').innerText()).slice(-5000)); throw error; }
  finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
